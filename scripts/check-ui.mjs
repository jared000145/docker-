import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.route('https://rectorplus-test.supabase.co/**', route => route.fulfill({ status: 200, contentType: 'application/json', body: '[]' }));
await page.goto('http://127.0.0.1:4173/login');
await page.getByRole('heading', { name: 'Bon retour !' }).waitFor();
await page.getByRole('button', { name: 'Nécessaires seulement' }).click();
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'mobile layout must not overflow');
await page.getByLabel('Langue / Language').selectOption('en');
await page.getByRole('heading', { name: 'Welcome back!' }).waitFor();
await page.getByRole('tab', { name: 'Email', exact: true }).click();
await page.getByRole('button', { name: 'Sign in', exact: true }).waitFor();
await page.reload();
await page.getByRole('heading', { name: 'Welcome back!' }).waitFor();
await page.locator('.glass-card-elevated').evaluate(async element => { await Promise.all(element.getAnimations().map(animation => animation.finished)); });
assert.equal(await page.locator('html').getAttribute('lang'), 'en');
await mkdir('.tools/screenshots', { recursive: true });
await page.screenshot({ path: '.tools/screenshots/login-mobile.png', fullPage: true });
await page.setViewportSize({ width: 1440, height: 1000 });
await page.screenshot({ path: '.tools/screenshots/login-desktop.png', fullPage: true });
assert.deepEqual(errors, [], 'no uncaught browser exceptions');
await browser.close();
console.log('PASS: mobile layout, language switch, persistence, email sign-in and browser runtime.');
